def example_6_cache_benefits():
    """Example: Demonstrasi cache performance"""
    print("\n" + "="*70)
    print("EXAMPLE 6: Cache Performance Demo")
    print("="*70 + "\n")
    
    client = OMPClientEnhanced()
    
    # Clear cache
    client.clear_cache()
    print("🗑️  Cache cleared\n")
    
    prompt = "Write a Python function to check if a port is open"
    
    import time
    
    # First request (uncached)
    print("📌 Request 1: Cold start (no cache)")
    start = time.time()
    result1 = client.query(prompt, template="code", use_cache=True)
    time1 = time.time() - start
    
    if result1['success']:
        print(f"   ⏱️  Time: {time1:.3f}s")
        print(f"   Provider: {result1['provider']}")
        print(f"   Cached: {result1['cached']}\n")
    
    # Second request (cached)
    print("📌 Request 2: Same prompt (should hit cache)")
    start = time.time()
    result2 = client.query(prompt, template="code", use_cache=True)
    time2 = time.time() - start
    
    if result2['success']:
        print(f"   ⏱️  Time: {time2:.3f}s")
        print(f"   Provider: {result2['provider']}")
        print(f"   Cached: {result2['cached']}")
        print(f"   🚀 Speedup: {time1/time2:.0f}x faster\n")
    
    # Show cache stats
    cache_files = list(client.cache_dir.glob("*.json"))
    total_size = sum(f.stat().st_size for f in cache_files)
    
    print(f"💾 Cache Stats:")
    print(f"   Files: {len(cache_files)}")
    print(f"   Total size: {total_size/1024:.1f} KB")
    print(f"   Location: {client.cache_dir}")

